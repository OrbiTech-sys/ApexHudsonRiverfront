import type { LedgerEntry, PortalData } from "@/types/portal";
import { formattedAddress, site } from "@/data/site";
import { formatMoney } from "@/lib/format";
import type { GeneratedFile } from "@/lib/demo/download";
import { formatIsoDate } from "@/lib/portal/dates";

/**
 * Generates SAMPLE document text for the demo portal. These are not legal
 * documents; they exist so "Download" does something real in the demo.
 */

const banner = [
  "SAMPLE DOCUMENT FOR THE APEX HUDSON RIVERFRONT DEMO PORTAL",
  "This is not a real lease or legal document. All names, amounts and dates are sample data.",
  "",
].join("\n");

export function buildDocument(id: string, data: PortalData): GeneratedFile | null {
  const { profile, lease } = data;
  const resident = `${profile.firstName} ${profile.lastName}`;

  switch (id) {
    case "doc-lease":
      return {
        filename: "sample-lease-summary.txt",
        content: [
          banner,
          "LEASE SUMMARY (SAMPLE)",
          `Property: ${site.name}, ${formattedAddress}`,
          `Resident: ${resident}`,
          `Home: ${lease.unitLabel} (${lease.planName})`,
          `Lease term: ${formatIsoDate(lease.startDate)} to ${formatIsoDate(lease.endDate)}`,
          `Monthly rent: ${formatMoney(lease.monthlyRent)} (illustrative)`,
          `Security deposit: ${formatMoney(lease.securityDeposit)} (illustrative)`,
          `Rent due: day ${lease.rentDueDay} of each month`,
          "",
          "A real lease would set out the full terms, rules and legal obligations of both parties.",
        ].join("\n"),
      };
    case "doc-move-in":
      return {
        filename: "sample-move-in-checklist.txt",
        content: [
          banner,
          "MOVE-IN CONDITION CHECKLIST (SAMPLE)",
          `Home: ${lease.unitLabel}`,
          "",
          "[ ] Walls and ceilings",
          "[ ] Floors",
          "[ ] Windows and locks",
          "[ ] Kitchen: counters, cabinets, appliances",
          "[ ] Bathroom: fixtures, tub or shower, ventilation",
          "[ ] Smoke and carbon monoxide alarms",
          "[ ] Keys and access devices received",
          "",
          "Notes:",
        ].join("\n"),
      };
    case "doc-guidelines":
      return {
        filename: "sample-community-guidelines.txt",
        content: [
          banner,
          "COMMUNITY GUIDELINES (SAMPLE)",
          "",
          "1. Be considerate of neighbors, especially during evening hours.",
          "2. Keep shared spaces clean and report anything that needs attention.",
          "3. Dispose of trash and recycling in the designated areas.",
          "4. Collect packages promptly.",
          "5. Report maintenance needs through the portal.",
        ].join("\n"),
      };
    case "doc-insurance":
      return {
        filename: "sample-renters-insurance-info.txt",
        content: [
          banner,
          "RENTERS INSURANCE INFORMATION (SAMPLE)",
          "",
          "Renters insurance protects your belongings and covers personal liability.",
          "Ask the leasing team what your lease requires. This sample does not state any requirement.",
        ].join("\n"),
      };
    default:
      return null;
  }
}

export function buildReceipt(entry: LedgerEntry, data: PortalData): GeneratedFile {
  const { profile, lease } = data;
  return {
    filename: `demo-receipt-${entry.reference ?? entry.id}.txt`,
    content: [
      banner,
      "PAYMENT RECEIPT (DEMO)",
      `Confirmation: ${entry.reference ?? entry.id}`,
      `Date: ${formatIsoDate(entry.date)}`,
      `Resident: ${profile.firstName} ${profile.lastName}`,
      `Home: ${lease.unitLabel}`,
      `Amount: ${formatMoney(entry.amount)}`,
      `Method: ${entry.method ?? "Demo payment method"}`,
      "",
      "No money was moved. This receipt is generated by a demonstration.",
    ].join("\n"),
  };
}
